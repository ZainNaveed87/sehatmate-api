// Closed diagnostic vocabulary only. Never print provider codes verbatim:
// even a code-shaped string can contain untrusted/user information.
const categories=new Set(['conversation','app_help','patient_read','navigation',
 'action','unsupported','ambiguous','ui_guidance','task_workflow','memory']);
const fixedCode=(codes,code)=>typeof code==='string'&&Object.hasOwn(codes,code)?codes[code]:'UNKNOWN';
export function logAgentPlanOutput(plan) {
 console.info(`AGENT_PLAN_OUTPUT:${categories.has(plan?.category)?plan.category.toUpperCase():'UNKNOWN'}`);
 console.info(`AGENT_PLAN_CREATE_INTENT:${plan?.intent==='create_care_plan'?'RECOGNIZED':'OTHER'}`);
}
export function logAgentPlanFailure(result) {
 const marker=fixedCode({AGENT_PLAN_INVALID:'SCHEMA',INVALID_CAPABILITY_ARGS:'ARGUMENTS',
  UNKNOWN_CAPABILITY:'UNKNOWN_CAPABILITY',INVALID_AGENT_CAPABILITY_CALLS:'CAPABILITY_SHAPE',
  AGENT_TOO_MANY_CAPABILITY_CALLS:'CAPABILITY_LIMIT',AGENT_PERMISSION_CLASS_NOT_EXECUTABLE:'PERMISSION',
  INVALID_NAVIGATION_INTENT:'NAVIGATION',AGENT_PRODUCT_FACT_SELECTION_INVALID:'PRODUCT_SELECTION',
  AGENT_PROVIDER_UNCONFIGURED:'PROVIDER_UNCONFIGURED',AGENT_PROVIDER_FAILED:'PROVIDER',
  AGENT_PROMPT_TOO_LARGE:'PROMPT_LIMIT',AGENT_UI_INVALID_OPERATIONS:'UI_OPERATIONS',
  AGENT_UI_STALE_CONTEXT:'UI_STALE'},result?.code);
 console.info(`AGENT_PLAN_FAILED:${marker}`);
}
export function agentMemoryFailureReason(error) {
 if(error instanceof SyntaxError)return 'SERIALIZATION';
 return fixedCode({ER_NO_SUCH_TABLE:'SCHEMA_TABLE',ER_BAD_FIELD_ERROR:'SCHEMA_COLUMN',
  ER_NO_REFERENCED_ROW_2:'FOREIGN_KEY',ER_ROW_IS_REFERENCED_2:'FOREIGN_KEY',
  ER_DUP_ENTRY:'DUPLICATE',ER_PARSE_ERROR:'QUERY',ER_WRONG_ARGUMENTS:'QUERY',
  ER_TRUNCATED_WRONG_VALUE:'VALUE_TYPE',ER_DATA_TOO_LONG:'VALUE_SIZE',
  ER_LOCK_DEADLOCK:'DEADLOCK',ER_LOCK_WAIT_TIMEOUT:'LOCK_TIMEOUT',
  ETIMEDOUT:'CONNECTION_TIMEOUT',ECONNRESET:'CONNECTION',ECONNREFUSED:'CONNECTION',
  PROTOCOL_CONNECTION_LOST:'CONNECTION',ER_ACCESS_DENIED_ERROR:'DB_AUTH',
  ER_TABLEACCESS_DENIED_ERROR:'DB_PERMISSION',ER_BAD_DB_ERROR:'DB_CONFIG',
  INVALID_AGENT_ID:'ACCOUNT_ID',AGENT_MEMORY_NOT_FOUND:'ACCOUNT_NOT_FOUND',
  AGENT_STORAGE_TRANSACTION_REQUIRED:'TRANSACTION_UNAVAILABLE',
  AGENT_MEMORY_STORAGE_UNAVAILABLE:'SCHEMA_UNAVAILABLE',INVALID_AGENT_MEMORY:'VALIDATION',
  AGENT_MEMORY_EVIDENCE_REQUIRED:'EVIDENCE',AGENT_MEMORY_CONFIRMATION_REQUIRED:'EVIDENCE',
  AGENT_MEMORY_VERIFIED_EVIDENCE_REQUIRED:'EVIDENCE',INVALID_AGENT_MEMORY_KIND:'VALIDATION',
  INVALID_AGENT_MEMORY_CONFIDENCE:'VALIDATION',INVALID_AGENT_MEMORY_EXPIRY:'VALIDATION',
  INVALID_AGENT_MEMORY_SENSITIVITY:'VALIDATION'},error?.code);
}
const memoryStages=new Set(['VALIDATION','TRANSACTION','ACCOUNT_LOCK','DEDUP_READ',
 'SUPERSEDE_READ','INSERT','SUPERSEDE_UPDATE','COMMIT_OR_RELEASE']);
export function logAgentMemoryWriteFailure(stage,error) {
 console.info(`AGENT_MEMORY_WRITE_FAILED:${memoryStages.has(stage)?stage:'UNKNOWN'}:${agentMemoryFailureReason(error)}`);
}
